import assert from 'node:assert/strict';
import { runAreaBrowserMatrix, activate } from './editor-area-browser.mjs';
import { recordRoom, recordText, recordShot } from './editor-record-browser.mjs';
import { drawWalls, panel, preserveTheme } from './editor-structure-check.mjs';
import { editorAccessibility } from './editor-accessibility.mjs';
const state = page => page.evaluate(() => window.editorFidelity.groups());
async function journey(page, scenario, out) {
	await recordRoom(page, scenario, out, { drawWalls, panel, preserveTheme });
	const before = await state(page); assert.equal(before.groups.length, 0);
	await activate(page, '[data-rp-group-action="enclose"]');
	await page.waitForFunction(() => window.editorFidelity.groups().groups.length === 1);
	let grouped = await state(page); assert.equal(grouped.structure.walls.length, before.structure.walls.length);
	assert.equal(grouped.groups[0].memberIds.length, 5);
	await recordShot(page, scenario, out, 'saved-room-assembly');
	if (scenario.width === 460) await page.keyboard.press('Escape');
	const corner = await page.evaluate(id => window.editorFidelity.rotationHoverPoint(id), grouped.rooms[0].id);
	const start = { x: corner.x + 50, y: corner.y + 50 }, end = { x: start.x + 70, y: start.y + 35 };
	await page.mouse.move(start.x, start.y); await page.mouse.down(); await page.mouse.move(end.x, end.y, { steps: 5 });
	await recordShot(page, scenario, out, 'assembly-drag-preview');
	await page.keyboard.press('Escape'); await page.mouse.up(); assert.deepEqual(await state(page), grouped);
	await page.mouse.move(start.x, start.y); await page.mouse.down(); await page.mouse.move(end.x, end.y, { steps: 5 }); await page.mouse.up();
	await page.waitForFunction(x => window.editorFidelity.groups().rooms[0].points[0].x !== x, grouped.rooms[0].points[0].x);
	const dragged = await state(page), dx = dragged.rooms[0].points[0].x - grouped.rooms[0].points[0].x, dy = dragged.rooms[0].points[0].y - grouped.rooms[0].points[0].y;
	assert.ok(Math.abs(dx) > 0 && Math.abs(dy) > 0);
	assert.equal(dragged.structure.walls[0].start.x - grouped.structure.walls[0].start.x, dx);
	assert.equal(dragged.structure.walls[0].start.y - grouped.structure.walls[0].start.y, dy);
	grouped = dragged; await panel(page, 'details');
	await recordText(page, '[data-rp-group-controls]', 'group-dx', '0,5');
	await recordText(page, '[data-rp-group-controls]', 'group-dy', '0,25');
	await activate(page, '[data-rp-group-controls] button[type="submit"]');
	await page.waitForFunction(([x, y]) => { const point = window.editorFidelity.groups().rooms[0].points[0]; return point.x === x + 500 && point.y === y + 250; }, [grouped.rooms[0].points[0].x, grouped.rooms[0].points[0].y]);
	const moved = await state(page); assert.equal(moved.structure.walls[0].start.x, grouped.structure.walls[0].start.x + 500);
	await activate(page, '[data-rp-group-transform="rotate"]');
	await recordText(page, '[data-rp-form="object-rotation"]', 'angle', '27,5');
	await recordShot(page, scenario, out, 'group-rotation-preview');
	const a11y = await editorAccessibility(page, scenario, out, 'group-rotation-preview');
	await page.keyboard.press('Escape'); await page.locator('[data-rp-form="object-rotation"]').waitFor({ state: 'hidden' });
	assert.deepEqual(await state(page), moved);
	await activate(page, '[data-rp-group-transform="right"]');
	await page.waitForFunction(expectedJson => JSON.stringify(window.editorFidelity.groups()) !== expectedJson, JSON.stringify(moved));
	await activate(page, '[data-rp-action="undo"]');
	await page.waitForFunction(expectedJson => JSON.stringify(window.editorFidelity.groups()) === expectedJson, JSON.stringify(moved));
	assert.deepEqual(await state(page), moved);
	await activate(page, '[data-rp-action="redo"]');
	await page.waitForFunction(expectedJson => JSON.stringify(window.editorFidelity.groups()) !== expectedJson, JSON.stringify(moved));
	await recordShot(page, scenario, out, 'rotated-room-assembly');
	await activate(page, '[data-rp-group-action="ungroup"]');
	await page.waitForFunction(() => window.editorFidelity.groups().groups.length === 0);
	await activate(page, '[data-rp-group-action="group"]');
	await page.waitForFunction(() => window.editorFidelity.groups().groups.length === 1);
	return { accessibility: [a11y], reusedBoundaryWalls: true, savedMembership: true, pointerAssemblyMove: true, dragCancelNoWrite: true, numericAssemblyMove: true, rotationCancelNoWrite: true, quarterTurnHistory: true,
		storage: 'Production commands and repositories over FakeVault; native acceptance is separate' };
}
await runAreaBrowserMatrix('editor-groups', '&reference&planning&fidelity', journey, '[data-rp-empty="floor-start"]');
